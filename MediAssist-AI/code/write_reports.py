def n(x):
    return f"{int(x):,}" if float(x) == int(x) else f"{x:,.3f}"


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for c in iter(lambda: fh.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


